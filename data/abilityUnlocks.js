// Keep the authored skills and artwork, but prevent learning, display and combat use.
export const DISABLED_ABILITY_IDS = new Set([
  "ability_v2_barmaid_tavern_brawl",
  "ability_v2_grovekeeper_entangling_roots"
]);

export function abilityEnabled(ability) {
  return Boolean(ability) && !ability.disabled && !DISABLED_ABILITY_IDS.has(ability.id);
}

export function abilityUnlockLevel(ability, className) {

  // Resolved class definitions carry starter eligibility into combat and UI checks.
  // Raw generic rows receive the exception only for a class that actually starts with it.
  if (ability.starter || CLASS_STARTER_KITS[className]?.includes(ability.id)) return 1;
  return ABILITY_UNLOCK_LEVELS[ability.id] ?? ability.minimumLevel ?? 1;
}

// Enemy skills have no adventurer level gate. Disabled skills stay disabled in saved battles.
export function abilityMeetsLevel(character, ability) {
  return abilityEnabled(ability) && (character.isEnemy
    || (character.level ?? 1) >= abilityUnlockLevel(ability));
}
