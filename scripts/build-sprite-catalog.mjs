import fs from 'node:fs';

// Each PixelLab sheet contains four facing rows of unmodified 256px frames.
const names = [
  'laurana', 'tika', 'tanis', 'sturm', 'goldmoon', 'caramon-gladiator',
  'raistlin', 'dalamar', 'palin', 'tasslehoff', 'flint', 'riverwind', 'fistandantilus', 'mishakal',
].filter(name => fs.existsSync(`assets/characters/${name}/reference-v2/sheets/layout.json`));
const directions = ['south-east', 'south-west', 'north-east', 'north-west'];
const timings = { idle: 150, walk: 75, attack: 70, block: 85, hit: 60, death: 110 };

// Tika's later front-facing idle frames contain a bright baked-in pan trail.
const frameOverrides = {
  tika: { idle: { 'south-east': [0, 1, 1, 0] } },
};
const facing = {
  south: 'south-east', 'south-east': 'south-east', east: 'south-east',
  'south-west': 'south-west', west: 'south-west', north: 'north-east',
  'north-east': 'north-east', 'north-west': 'north-west',
};
const definitions = [];
const textures = [];
for (const name of names) {
  const root = `assets/characters/${name}/reference-v2/sheets`;
  const layout = JSON.parse(fs.readFileSync(`${root}/layout.json`, 'utf8'));
  if (layout.frameWidth !== 256 || layout.frameHeight !== 256 ||
      JSON.stringify(layout.directions) !== JSON.stringify(directions)) {
    throw new Error(`Unexpected sprite sheet layout: ${name}`);
  }
  const clips = {};
  for (const [state, frameMs] of Object.entries(timings)) {
    const sheet = layout.states[state];
    if (!sheet) throw new Error(`Missing sprite sheet state: ${name}/${state}`);
    const key = `${name}-reference-v2-${state}`;
    const file = `${root}/${state}.png`;
    if (!fs.existsSync(file)) throw new Error(`Missing sprite sheet: ${file}`);
    textures.push({ name, key, file });
    const authored = Object.fromEntries(directions.map((direction, row) => {
      const count = sheet.counts[direction];
      if (!Number.isInteger(count) || count < 4 || count > sheet.columns) {
        throw new Error(`Incomplete animation: ${name}/${state}/${direction}`);
      }
      const columns = frameOverrides[name]?.[state]?.[direction] ?? Array.from({ length: count }, (_, column) => column);
      return [direction, {
        frameMs,
        frames: columns.map(column => ({
          key, frame: row * sheet.columns + column,
          originX: 0.5, originY: 238 / 256, flipX: false,
        })),
      }];
    }));
    clips[state] = Object.fromEntries(Object.entries(facing).map(([heading, direction]) => [heading, authored[direction]]));
  }
  clips.dead = Object.fromEntries(Object.entries(clips.death).map(([heading, clip]) =>
    [heading, { frameMs: 1000, frames: [clip.frames.at(-1)] }]));
  definitions.push(`${JSON.stringify(name)}:{textures:textures.filter(t=>t.character===${JSON.stringify(name)}),clips:${JSON.stringify(clips)},scale:0.66,footY:30}`);
}
const source = `// Generated by scripts/build-sprite-catalog.mjs from PixelLab sprite sheets.\nconst textures=[\n${textures.map(t =>
  `{character:${JSON.stringify(t.name)},key:${JSON.stringify(t.key)},url:new URL(${JSON.stringify('../' + t.file)},import.meta.url).href}`
).join(',\n')}\n];\nexport const CHARACTER_SPRITES={${definitions.join(',\n')}};\nexport function preloadCharacterSprites(scene){\n  for(const {key,url} of textures) if(!scene.textures.exists(key)) scene.load.spritesheet(key,url,{frameWidth:256,frameHeight:256});\n}\n`;
fs.writeFileSync('data/characterSprites.js', source);
console.log(`Wrote ${names.length} characters and ${textures.length} sprite sheets.`);
