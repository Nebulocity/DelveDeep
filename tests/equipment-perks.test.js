// Exercise strict thresholds and attack scopes with live resources, not fixed stat totals.
import assert from 'node:assert/strict';
import { equipmentPerkBonus, equipmentPerkDescription } from '../game/EquipmentPerks.js';
import { getEquipmentDefinition } from '../data/items.js';
import { equipmentDetails } from '../game/EquipmentDescriptions.js';
import { getEquippedAdventurer, grantEquipment, equipItem } from '../game/Equipment.js';
import GameState from '../game/GameState.js';
import adventurers from '../data/adventurers.js';
import { loadProfile } from '../game/GameStorage.js';

const actor = { id: 'actor', alive: true, hp: 100, maxHp: 100, mana: 100, maxMana: 100 };
const ally = { id: 'ally', alive: true, hp: 100, maxHp: 100 };
const enemy = { id: 'enemy', alive: true, isEnemy: true, hp: 100, maxHp: 100, currentTargetId: actor.id };
const setPerk = id => { actor.equipmentPerks = [{ ...getEquipmentDefinition(id).perk }]; };
const bonus = (kind, target = enemy, context = {}) => equipmentPerkBonus(actor, kind, target, [actor, ally], context);
setPerk('R1D01');
assert.equal(bonus('crit'), 0);
enemy.hp = 50;
assert.equal(bonus('crit'), 0);
enemy.hp = 49;
assert.equal(bonus('crit'), 0.05);
assert.equal(bonus('crit', ally), 0);
assert.equal(bonus('damage'), 0);
setPerk('R1L01');
actor.hp = 50;
assert.equal(bonus('block'), 0);
actor.hp = 49;
assert.equal(bonus('block'), 0.1);
setPerk('R1S01');
assert.equal(bonus('damage', enemy, { basic: true }), 0.1);
assert.equal(bonus('damage', enemy, { spell: true }), 0);
enemy.currentTargetId = ally.id;
assert.equal(bonus('damage', enemy, { basic: true }), 0);
setPerk('R1A01');
actor.hp = 100;
assert.equal(bonus('damage', enemy, { basic: true }), 0.1);
ally.hp = 50;
assert.equal(bonus('damage', enemy, { basic: true }), 0);
ally.alive = false;
assert.equal(bonus('damage', enemy, { basic: true }), 0.1);
ally.alive = true;
setPerk('R1G01');
ally.hp = 25;
assert.equal(bonus('damage'), 0);
ally.hp = 24;
assert.equal(bonus('damage'), 0.15);
enemy.currentTargetId = actor.id;
actor.hp = 20;
assert.equal(bonus('damage'), 0);
enemy.currentTargetId = ally.id;
assert.equal(bonus('damage', enemy, { reflection: true }), 0);
setPerk('R1M01');
assert.equal(bonus('healing', ally), 0.15);
ally.hp = 50;
assert.equal(bonus('healing', ally), 0);
setPerk('R1T01');
actor.mana = 50;
assert.equal(bonus('damage', enemy, { spell: true }), 0);
actor.mana = 51;
assert.equal(bonus('damage', enemy, { spell: true }), 0.1);
assert.equal(bonus('damage', enemy, { basic: true }), 0);
setPerk('R1B01');
enemy.hp = 51;
assert.equal(bonus('damage', enemy, { basic: true }), 0.1);
enemy.hp = 50;
assert.equal(bonus('damage', enemy, { basic: true }), 0);

// Armor has the same strict boundary behavior and does not change permanent stats.
for (const [itemId, kind, activeHp] of [['R1AP01', 'reduction', 49], ['R1AL01', 'dodge', 51], ['UMI007', 'receivedHealing', 49]]) {
  setPerk(itemId);
  actor.hp = activeHp;
  assert.ok(bonus(kind) > 0);
  actor.hp = 50;
  assert.equal(bonus(kind), 0);
}
setPerk('UMI006');
actor.mana = 49;
assert.equal(bonus('damage', enemy, { spell: true }), 0.1);
actor.mana = 50;
assert.equal(bonus('damage', enemy, { spell: true }), 0);
assert.equal(equipmentPerkBonus({ ...actor, equipmentPerks: undefined }, 'damage', enemy), 0);
assert.equal(equipmentPerkBonus({ ...actor, isEnemy: true }, 'damage', enemy), 0);

globalThis.localStorage = { getItem: () => null, setItem() {} };
loadProfile(adventurers);
const hero = GameState.roster.find(hero => hero.className === 'Gladiator');
hero.level = 20;
const sword = grantEquipment('R1L01');
assert.equal(equipItem(hero.id, sword.id).ok, true);
const departing = getEquippedAdventurer(hero);
assert.equal(departing.equipmentPerks[0].id, 'live_to_tell');
assert.notEqual(departing.equipmentPerks[0], getEquipmentDefinition('R1L01').perk);
assert.match(equipmentDetails(sword).description, /Live to Tell: \+10% Block/);
assert.match(equipmentDetails(sword).description, /Captain Dorran/);
assert.match(equipmentPerkDescription(getEquipmentDefinition('UMI007').perk), /Receive 15% more healing/);
console.log('All eight weapon and four armor perks, thresholds, scopes, frozen copies and inspection text passed.');
